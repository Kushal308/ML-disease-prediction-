import React, { useState } from 'react';
import { DISEASES } from '../utils/diseaseConfig';
import { DiseaseCard } from '../components/DiseaseCard';
import { DiseaseKey } from '../types/disease';
import { Search, Filter, ShieldAlert } from 'lucide-react';

interface DiseaseSelectionPageProps {
  onSelectDisease: (key: DiseaseKey) => void;
}

export const DiseaseSelectionPage: React.FC<DiseaseSelectionPageProps> = ({ onSelectDisease }) => {
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState<string>('all');

  const categories = [
    { id: 'all', label: 'All Models' },
    { id: 'Cardiovascular', label: 'Cardiovascular' },
    { id: 'Metabolic', label: 'Metabolic' },
    { id: 'Renal', label: 'Renal' },
    { id: 'Hepatic', label: 'Hepatic' },
    { id: 'Cerebrovascular', label: 'Cerebrovascular' },
  ];

  const diseaseList = Object.values(DISEASES).filter((disease) => {
    const matchesSearch =
      disease.title.toLowerCase().includes(searchTerm.toLowerCase()) ||
      disease.description.toLowerCase().includes(searchTerm.toLowerCase()) ||
      disease.subtitle.toLowerCase().includes(searchTerm.toLowerCase());

    const matchesCategory =
      selectedCategory === 'all' || disease.badge.toLowerCase() === selectedCategory.toLowerCase();

    return matchesSearch && matchesCategory;
  });

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-10">
      
      {/* Header */}
      <div className="text-center max-w-2xl mx-auto space-y-3">
        <span className="text-xs font-bold uppercase tracking-wider px-3 py-1 rounded-full bg-mediblue-100 text-mediblue-800">
          Clinical Prediction Models
        </span>
        <h1 className="text-3xl sm:text-4xl font-black text-slate-900 tracking-tight">
          Select Disease Risk Predictor
        </h1>
        <p className="text-xs sm:text-sm text-slate-600">
          Choose a condition to input health parameters and evaluate statistical risk using our trained machine learning models.
        </p>
      </div>

      {/* Mandatory Non-Diagnosis Medical Disclaimer */}
      <div className="p-4 rounded-2xl bg-amber-500/10 border border-amber-500/20 text-amber-900 text-xs flex items-center gap-3">
        <ShieldAlert className="w-5 h-5 text-amber-600 shrink-0" />
        <p>
          <strong>Medical Notice:</strong> Predictions are statistical risk estimations generated by machine learning algorithms and are NOT diagnostic evaluations. Always consult a licensed medical practitioner.
        </p>
      </div>

      {/* Search and Category Filter Toolbar */}
      <div className="flex flex-col sm:flex-row items-center justify-between gap-4">
        {/* Search Input */}
        <div className="relative w-full sm:w-80">
          <Search className="w-4 h-4 text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder="Search condition or biomarker..."
            value={searchTerm}
            onChange={(e) => setSearchTerm(e.target.value)}
            className="w-full pl-10 pr-4 py-2.5 rounded-2xl border border-slate-200 bg-white text-xs font-medium focus:outline-none focus:ring-2 focus:ring-mediblue-500 shadow-sm"
          />
        </div>

        {/* Category Pills */}
        <div className="flex items-center gap-1.5 overflow-x-auto w-full sm:w-auto pb-1 sm:pb-0">
          {categories.map((cat) => (
            <button
              key={cat.id}
              onClick={() => setSelectedCategory(cat.id)}
              className={`px-3.5 py-2 rounded-xl text-xs font-semibold whitespace-nowrap transition-all ${
                selectedCategory === cat.id
                  ? 'bg-slate-900 text-white shadow-sm'
                  : 'bg-white border border-slate-200 text-slate-600 hover:bg-slate-50'
              }`}
            >
              {cat.label}
            </button>
          ))}
        </div>
      </div>

      {/* Diseases Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
        {diseaseList.map((disease) => (
          <DiseaseCard
            key={disease.key}
            config={disease}
            onSelect={(key) => onSelectDisease(key as DiseaseKey)}
          />
        ))}
      </div>

      {diseaseList.length === 0 && (
        <div className="text-center py-16 bg-white rounded-3xl border border-slate-200 p-8 space-y-3">
          <p className="text-sm font-bold text-slate-700">No matching disease models found</p>
          <p className="text-xs text-slate-400">Try adjusting your search criteria or category filter.</p>
          <button
            onClick={() => { setSearchTerm(''); setSelectedCategory('all'); }}
            className="px-4 py-2 rounded-xl bg-slate-100 text-slate-700 text-xs font-bold hover:bg-slate-200 transition"
          >
            Reset Filters
          </button>
        </div>
      )}

    </div>
  );
};
